"""Regenerate the README results tables from the result CSVs (never edit them by hand).

    python scripts/make_tables.py            # rewrites the block between the markers in README.md
    python scripts/make_tables.py --check    # exit 1 if README.md is out of date (for CI)

Reads results/e1/metrics.csv, results/e1/threshold_wrn50.csv (dev, with LOCO),
results/e1/threshold_wrn50_held_out.csv and results/anomalib_reference.csv.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from visionguard.config import load_split

START = "<!-- results:start (generated by scripts/make_tables.py; do not edit by hand) -->"
END = "<!-- results:end -->"


def _f(x: float) -> str:
    return f"{x:.3f}"


def e1_table(metrics: pd.DataFrame, thr: pd.DataFrame, cats: list[str], loco: bool) -> str:
    head = "| Category | Image AUROC | Pixel AUROC | AU-PRO | FPR @ 95% recall (oracle) | "
    head += "Recall at m | False rejects at m |"
    if loco:
        head += " Recall at m, leave-one-out |"
    lines = [head, "|" + "---|" * (8 if loco else 7)]
    t = thr.set_index("category")
    m = metrics.set_index("category")
    for c in cats:
        r = m.loc[c]
        row = (
            f"| {c} | {_f(r.image_auroc)} | {_f(r.pixel_auroc)} | {_f(r.au_pro)} | "
            f"{_f(r.fpr_at_95_recall)} | {_f(t.loc[c, 'recall'])} | {_f(t.loc[c, 'fpr'])} |"
        )
        if loco:
            row += f" {_f(t.loc[c, 'loco_recall'])} |"
        lines.append(row)
    sel, ts = m.loc[cats], t.loc[cats]
    mean = (
        f"| **Mean** | **{_f(sel.image_auroc.mean())}** | **{_f(sel.pixel_auroc.mean())}** | "
        f"**{_f(sel.au_pro.mean())}** | **{_f(sel.fpr_at_95_recall.mean())}** | "
        f"**{_f(ts.recall.mean())}** | **{_f(ts.fpr.mean())}** |"
    )
    if loco:
        mean += f" **{_f(ts.loco_recall.mean())}** |"
    lines.append(mean)
    return "\n".join(lines)


def build(root: Path) -> str:
    split = load_split(root / "configs" / "split.yaml")
    metrics = pd.read_csv(root / "results" / "e1" / "metrics.csv")
    main = metrics[(metrics.backbone == "wrn50") & (metrics.calibration_fraction == 0.1)]
    dev_thr = pd.read_csv(root / "results" / "e1" / "threshold_wrn50.csv")
    held_thr = pd.read_csv(root / "results" / "e1" / "threshold_wrn50_held_out.csv")
    margin = float(held_thr.margin.iloc[0])

    parts = [
        "### Development categories (used to choose settings)",
        "",
        e1_table(main, dev_thr, list(split.dev), loco=True),
        "",
        "### Held-out categories (independent test, every setting frozen)",
        "",
        e1_table(main, held_thr, list(split.held_out), loco=False),
        "",
        f"m = {margin:.2f}: threshold = (1 + m) × the highest score among each category's "
        "held-back defect-free calibration images, so no defect is seen. m was tuned on the "
        "development categories, so their columns at m are tuning diagnostics; the "
        "leave-one-out column chooses m on the other nine development categories. On the "
        "held-out categories m is frozen, so those columns are an independent test.",
    ]
    ref_path = root / "results" / "anomalib_reference.csv"
    if ref_path.is_file():
        ref = pd.read_csv(ref_path).set_index("category")
        full = metrics[(metrics.backbone == "wrn50") & (metrics.calibration_fraction == 0.0)]
        full = full.set_index("category")
        rows = [
            "| Category | Image AUROC (ours / anomalib) | Pixel AUROC (ours / anomalib) "
            "| AU-PRO (ours / anomalib) |",
            "|---|---|---|---|",
        ]
        for c in ref.index:
            if c not in full.index:
                continue
            o, a = full.loc[c], ref.loc[c]
            rows.append(
                f"| {c} | {_f(o.image_auroc)} / {_f(a.image_auroc)} | "
                f"{_f(o.pixel_auroc)} / {_f(a.pixel_auroc)} | {_f(o.au_pro)} / {_f(a.au_pro)} |"
            )
        parts += [
            "",
            "### Check against anomalib 2.7 (same settings, every training image as reference)",
            "",
            "\n".join(rows),
        ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--root", default=".")
    p.add_argument("--readme", default="README.md")
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)

    root = Path(args.root)
    readme = root / args.readme
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{readme} has no results markers.")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = before + START + "\n" + build(root) + "\n" + END + after
    if args.check:
        if new != text:
            print("README results are out of date; run scripts/make_tables.py", file=sys.stderr)
            return 1
        return 0
    readme.write_text(new, encoding="utf-8")
    print(f"Updated {readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
